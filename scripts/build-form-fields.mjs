// Builds site/form-fields/frame.html + site/form-fields/panda.css + site/form-fields/states.js
// from scripts/form-fields/dump/.
//
// The dump is the real PiperX field request (FieldRequest) as fireball renders it, one capture
// per display mode and field state (see scripts/form-fields/zz_form_fields_static_dump.test.tsx),
// so the markup carries the app's own hashed Panda class names and panda.css is the app's own
// stylesheet for them.
//
// The frame shows one display mode: every field state, top to bottom, each in its own open
// shadow root with the widget's stylesheet inside, as the messenger's fields sit on a
// customer's page. So :host rules and inherited custom properties behave as in production.
//
//   npm run form-fields:build     # rebuild from the committed dump
//   npm run form-fields:refresh   # re-capture from fireball first, then build
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("..", import.meta.url));
const dump = `${repo}scripts/form-fields/dump`;
const out = `${repo}site/form-fields`;

const read = (name) => readFileSync(`${dump}/${name}`, "utf8");
// anchored: the <mode>--<field> captures taken from the chat timeline. Open messengers show
// picklists there, under the agent's question, not in the input area.
const { modes, fields, anchored = [], themes = [] } = JSON.parse(read("states.json"));
// themes: the --q-* custom properties Piper sets on the host for each theme (applyThemeCssVars).
// The first is the default; one with no vars renders the stylesheet's fallbacks.
const sha = existsSync(`${dump}/fireball-sha.txt`) ? read("fireball-sha.txt").trim() : "unknown";

// One change to the capture: autofocus is dropped. The frame shows every field at once, and
// the first one would otherwise take focus (and scroll) on load. Nothing else is changed.
const markup = (mode, field) => {
  const html = read(`${mode}--${field}.html`);
  if (!html.includes("FieldRequest.InputRow")) throw new Error(`${mode}--${field}.html has no field; the capture is empty.`);
  return html.replace(/\sautofocus(="[^"]*")?/gi, "");
};

mkdirSync(out, { recursive: true });
copyFileSync(`${dump}/panda.css`, `${out}/panda.css`);
writeFileSync(
  `${out}/states.js`,
  "// GENERATED by scripts/build-form-fields.mjs: the captured modes and field states the Form fields page offers.\n" +
    `window.PASTURE_FORM_FIELDS = ${JSON.stringify({ sha, modes, fields, anchored, themes: themes.map(({ id, label }) => ({ id, label })) }, null, 2)};\n`,
);

const templates = modes
  .flatMap((mode) =>
    fields.map(
      (field) =>
        `    <!-- ${mode.label}: ${field.label} -->\n    <template id="state-${mode.id}--${field.id}">${markup(mode.id, field.id)}</template>`,
    ),
  )
  .join("\n");

const frame = `<!doctype html>
<!-- GENERATED by scripts/build-form-fields.mjs from fireball ${sha}. Don't edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>PiperX form fields (static)</title>
    <!-- Inter, the messenger's font. Production's host.string.scss only declares Inter's
         @font-face rules in the light DOM; this is the same font from Google. -->
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" />
    <style>
      /* Frame only: the page around the fields, not the widget. */
      html,
      body {
        margin: 0;
      }
      body {
        padding: 16px 0 32px;
        font: 12px/1.4 ui-monospace, SFMono-Regular, Menlo, monospace;
        color: #6b5d4f;
      }
      /* Sidebar fields sit on the messenger's white panel; the collapsed card floats on the
         customer's page. */
      body[data-mode="sidebar"] {
        background: #fff;
      }
      body[data-mode="collapsed-right"] {
        background: #e9e2d6;
      }
      .state {
        margin: 0 0 20px;
      }
      .state__label {
        margin: 0 16px 6px;
      }
      body[data-mode="collapsed-right"] .state__host {
        display: block;
        margin-inline: 16px;
      }
      /* Timeline captures: the messenger's timeline insets its entries 24px from the panel
         edges (measured in a full Main render). The input area sets its own inset. */
      .state[data-anchored] .state__host {
        display: block;
        margin-inline: 24px;
      }
    </style>
  </head>
  <body>
    <div id="states"></div>

${templates}

    <script>
      (() => {
        const MODES = ${JSON.stringify(modes.map(({ id }) => id))};
        const FIELDS = ${JSON.stringify(fields.map(({ id, label }) => ({ id, label })))};
        const ANCHORED = ${JSON.stringify(anchored)};
        const THEMES = ${JSON.stringify(Object.fromEntries(themes.map(({ id, vars }) => [id, vars])))};
        const params = new URLSearchParams(location.search);
        const mode = MODES.includes(params.get("mode")) ? params.get("mode") : MODES[0];
        const theme = params.get("theme") in THEMES ? params.get("theme") : Object.keys(THEMES)[0];
        // ?field= limits the frame to one or more states (comma-separated); unset shows all.
        const only = (params.get("field") || "").split(",").filter(Boolean);
        const shown = only.length ? FIELDS.filter((f) => only.includes(f.id)) : FIELDS;
        if (!HTMLElement.prototype.attachShadow) {
          document.body.textContent = "This browser has no shadow DOM.";
          return;
        }
        document.body.dataset.mode = mode;
        document.getElementById("states").replaceChildren(
          ...shown.map((field) => {
            const section = document.createElement("section");
            section.className = "state";
            section.id = field.id;
            const label = document.createElement("p");
            label.className = "state__label";
            const anchored = ANCHORED.includes(mode + "--" + field.id);
            if (anchored) section.dataset.anchored = "";
            label.textContent = anchored ? field.label + " (in the timeline)" : field.label;
            const host = document.createElement("div");
            host.className = "state__host";
            host.dataset.state = field.id;
            // The theme, as Piper sets it: custom properties on the host, inherited into the shadow root.
            for (const [name, value] of Object.entries(THEMES[theme] || {})) host.style.setProperty(name, value);
            const root = host.attachShadow({ mode: "open", delegatesFocus: true });
            const sheet = document.createElement("link");
            sheet.rel = "stylesheet";
            sheet.href = "panda.css";
            // Insert the markup once the stylesheet has loaded, as in production, where the
            // widget's CSS is in place before a field renders. Inserted first, rules like the
            // multi-picklist's "transition: all" animate from browser defaults to the real styles.
            const content = document.getElementById("state-" + mode + "--" + field.id).content.cloneNode(true);
            const insert = () => root.append(content);
            sheet.addEventListener("load", insert, { once: true });
            sheet.addEventListener("error", insert, { once: true });
            root.append(sheet);
            // Nothing is wired to the form: keep a submit from reloading the frame.
            root.addEventListener("submit", (event) => event.preventDefault());
            section.append(label, host);
            return section;
          }),
        );
      })();
    </script>
  </body>
</html>
`;

writeFileSync(`${out}/frame.html`, frame);
console.log(
  `Built site/form-fields/frame.html (${modes.length} modes x ${fields.length} fields) and panda.css from fireball ${sha}`,
);
