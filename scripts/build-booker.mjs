// Builds site/booker/frame.html + site/booker/panda.css from scripts/booker/dump/.
//
// The dump is the real PiperX booker as fireball renders it (see
// scripts/booker/zz_booker_static_dump.test.tsx), so the markup carries the app's
// own hashed Panda class names and panda.css is the app's own stylesheet for them.
// Nothing here is hand-styled except the frame's backdrop and the optional
// CSS-only patch, which is clearly separated so it can be toggled.
//
//   npm run booker:build     # rebuild from the committed dump
//   npm run booker:refresh   # re-capture from fireball first, then build
import { mkdirSync, readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("..", import.meta.url));
const dump = `${repo}scripts/booker/dump`;
const out = `${repo}site/booker`;

const read = (name) => readFileSync(`${dump}/${name}`, "utf8");
const shippedMobile = read("shipped-mobile.html");
const shippedDesktop = read("shipped-desktop.html");
const fixed = read("fixed.html");
const slotClasses = JSON.parse(read("slot-classes.json"));
const sha = existsSync(`${dump}/fireball-sha.txt`) ? read("fireball-sha.txt").trim() : "unknown";

mkdirSync(out, { recursive: true });
copyFileSync(`${dump}/panda.css`, `${out}/panda.css`);

const frame = `<!doctype html>
<!-- GENERATED by scripts/build-booker.mjs from fireball ${sha}. Don't edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>PiperX meeting booker (static)</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" />
    <!-- The app's own Panda CSS for these components. -->
    <link rel="stylesheet" href="panda.css" />
    <style>
      /* Frame only: the page behind the lightbox, and the brand colour the widget
         host would normally set from the team's theme. */
      :root {
        --q-primary-color: #6a3f8e;
      }
      html,
      body {
        margin: 0;
        min-height: 100%;
        background: #e9e2d6;
      }
    </style>
    <!-- Candidate CSS-only patch for the time pill. Off unless ?patch=1. -->
    <style id="css-patch" media="not all">
      [data-component-name="MeetingTimeSelector.SlotButton"] {
        white-space: nowrap;
        height: auto;
        min-height: 36px;
        padding-inline: 4px;
      }
    </style>
  </head>
  <body>
    <div id="qualified-multimodal-host"></div>

    <!-- LightboxExperience as the captured fireball checkout renders it, on a phone and on a desktop. -->
    <template id="shipped-mobile">${shippedMobile}</template>
    <template id="shipped-desktop">${shippedDesktop}</template>

    <!-- The desktop lightbox with the "small" (mobile) MeetingTimeSelector swapped in: a preview of the layout fix. -->
    <template id="fixed">${fixed}</template>

    <script>
      (() => {
        const params = new URLSearchParams(location.search);
        // isMobile is the app's (max-width: 767px) query. Each frame picks the
        // capture for its own width, and re-picks on resize like the app's signal.
        // "fixed" previews the layout fix: the small layout, on narrow frames only.
        const fixed = params.get("variant") === "fixed";
        const mobile = matchMedia("(max-width: 767px)");
        const host = document.getElementById("qualified-multimodal-host");
        const mount = () => {
          const template = !mobile.matches ? "shipped-desktop" : fixed ? "fixed" : "shipped-mobile";
          if (host.dataset.template === template) return;
          host.dataset.template = template;
          host.replaceChildren(document.getElementById(template).content.cloneNode(true));
        };
        mount();
        mobile.addEventListener("change", mount);

        if (params.get("patch") === "1") document.getElementById("css-patch").media = "all";
        const primary = params.get("primary");
        if (primary) document.documentElement.style.setProperty("--q-primary-color", primary);

        // Static markup has no Preact behind it. Re-create slot selection by
        // swapping the two class lists the app renders for SlotButton.
        const SELECTED = ${JSON.stringify(slotClasses.selected)};
        const UNSELECTED = ${JSON.stringify(slotClasses.unselected)};
        const SLOT = '[data-component-name="MeetingTimeSelector.SlotButton"]';
        host.addEventListener("click", (event) => {
          const button = event.target.closest(SLOT);
          if (!button) return;
          for (const slot of host.querySelectorAll(SLOT)) {
            slot.className = UNSELECTED;
            slot.setAttribute("aria-pressed", "false");
          }
          button.className = SELECTED;
          button.setAttribute("aria-pressed", "true");
        });
      })();
    </script>
  </body>
</html>
`;

writeFileSync(`${out}/frame.html`, frame);
console.log(`Built site/booker/frame.html + panda.css from fireball ${sha}`);
