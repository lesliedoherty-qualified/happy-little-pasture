// Builds site/self-hosted.html from site/index.html and the self-hosted package in site/qualified/.
//
// The install block is copied verbatim from the package README (the HTML a customer pastes),
// with the README's placeholder asset host replaced by this site's qualified/ folder. That keeps
// View Source honest: the page shows exactly the tags the README tells customers to use.
//
//   node scripts/self-hosted/build-page.mjs     (usually through npm run self-hosted)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PAGES } from "./pages.mjs";

const repo = fileURLToPath(new URL("../..", import.meta.url));
const site = `${repo}site`;
const readmePath = `${site}/qualified/README.md`;
const infoPath = `${site}/qualified/package-info.json`;
const PLACEHOLDER_HOST = "https://assets.your-company.com/qualified/";

if (!existsSync(readmePath)) {
  console.error(`No package at ${readmePath}. Run npm run self-hosted first.`);
  process.exit(1);
}

const readme = readFileSync(readmePath, "utf8");
const intro = readme.indexOf("Add these tags to your HTML `<head>`");
const fenceStart = intro >= 0 ? readme.indexOf("```html\n", intro) : -1;
const fenceEnd = fenceStart >= 0 ? readme.indexOf("\n```", fenceStart + 8) : -1;
if (fenceEnd < 0) {
  console.error("Couldn't find the install HTML block in the package README.");
  process.exit(1);
}
const install = readme.slice(fenceStart + 8, fenceEnd);
if (!install.includes(PLACEHOLDER_HOST)) {
  console.error(`The README install block no longer uses ${PLACEHOLDER_HOST}; update this script.`);
  process.exit(1);
}
const localInstall = install.replaceAll(PLACEHOLDER_HOST, "qualified/");

const info = existsSync(infoPath) ? JSON.parse(readFileSync(infoPath, "utf8")) : {};
const escape = (value) =>
  String(value ?? "unknown").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const flagOn = /### Saved messenger setup/.test(readme);
const settings = info.savedSettings ? JSON.stringify(info.savedSettings) : "none (flag off or nothing saved)";

const indent = (text, spaces) =>
  text
    .split("\n")
    .map((line) => (line ? " ".repeat(spaces) + line : line))
    .join("\n");


// Gives a generated page its own name, H1, palette (via data-page) and current menu item.
function brand(html, id) {
  const meta = PAGES[id];
  const checks = [
    [/<html lang="en" data-page="hosted">/, `<html lang="en" data-page="${id}">`],
    [/<title>[^<]*<\/title>/, `<title>${meta.title}</title>`],
    [/<p class="eyebrow">[^<]*<\/p>(\s*)<h1>[^<]*<\/h1>/, `<p class="eyebrow">${meta.eyebrow}</p>$1<h1>${meta.h1}</h1>`],
    [/ data-nav="hosted" aria-current="page"/, ' data-nav="hosted"'],
    [new RegExp(` data-nav="${id}" data-local-only`), ` data-nav="${id}" data-local-only aria-current="page"`],
    [/<p class="harness__title">[^<]*<\/p>/, `<p class="harness__title">${meta.panel}</p>`],
  ];
  for (const [pattern, replacement] of checks) {
    if (!pattern.test(html)) {
      console.error(`index.html changed (no match for ${pattern}); update build-page.mjs.`);
      process.exit(1);
    }
    html = html.replace(pattern, replacement);
  }
  return html;
}

let page = readFileSync(`${site}/index.html`, "utf8");

const loader = /    <!-- Piper goes first[^\n]*\n    <script src="config\.js"><\/script>\n    <script src="js\/piper-loader\.js"><\/script>\n/;
if (!loader.test(page)) {
  console.error("index.html's Piper loader lines changed; update this script.");
  process.exit(1);
}
page = page.replace(
  loader,
  () =>
    "    <!-- Self-hosted Qualified install, copied verbatim from site/qualified/README.md.\n" +
    "         Generated by npm run self-hosted; don't edit by hand. -->\n" +
    indent(localInstall, 4) +
    "\n    <!-- End of self-hosted Qualified install. -->\n",
);

const harness = '<section id="harness" class="harness" aria-label="Test harness"></section>';
if (!page.includes(harness)) {
  console.error("index.html's harness section changed; update this script.");
  process.exit(1);
}
const row = (label, value) =>
  `          <div class="harness__row"><span class="harness__label">${label}</span><span class="harness__value">${value}</span></div>`;
page = page.replace(
  harness,
  [
    '<section id="harness" class="harness" aria-label="Self-hosted package">',
    '          <p class="harness__title">Self-hosted package</p>',
    row("README", flagOn ? "Saved messenger setup (flag on)" : "Legacy, no saved setup (flag off)"),
    row("Saved settings", `<code>${escape(settings)}</code>`),
    row("Exported", escape(info.exportedAt)),
    row("Widget build", escape(info.build?.builtAt)),
    row("Head / main", `${escape(info.head)} / ${escape(info.js)}`),
    '          <p class="harness__note">Reset between rows with a fresh incognito window: Piper remembers dock choices. ' +
      '<a href="./">Hosted install page</a> · <a href="qualified/README.md">Package README</a></p>',
    "        </section>",
  ].join("\n"),
);
page = page.replace('    <script src="js/harness.js" defer></script>\n', "");

writeFileSync(`${site}/self-hosted.html`, brand(page, "self-hosted"));
console.log(`Wrote site/self-hosted.html (${flagOn ? "flag on" : "flag off"} README, settings ${settings})`);

// Variant: the customer adds the head script but not the inline init/sentinel block after it,
// expecting Settings to drive everything through the runtime configuration.
const inlineInit = /\n[ ]*<script type="text\/javascript">\n(?:(?!<\/script>)[\s\S])*?qualified\.sentinel\.init\(\);\n[ ]*<\/script>\n/;
if (inlineInit.test(page)) {
  const noInit = page
    .replace(inlineInit, "\n    <!-- No inline docking/sentinel init: Settings reach the page only through runtime configuration. -->\n");
  writeFileSync(`${site}/self-hosted-no-init.html`, brand(noInit, "self-hosted-no-init"));
  console.log("Wrote site/self-hosted-no-init.html (head script without the inline init block)");
}

// Variant: self-hosted main widget and CSS, but the head comes from Qualified's token-aware
// docking.js, which embeds the team's current saved settings. No copied init to keep in sync.
const localHead = /[ ]*<script src="qualified\/qualified-head-[^"]+\.js" type="text\/javascript"><\/script>\n/;
if (info.token && localHead.test(page)) {
  const host = process.env.QUALIFIED_HOST || "http://localhost:34214";
  const tokenHead = page
    .replace(inlineInit, "\n")
    .replace(
      localHead,
      `    <script src="${host}/docking.js?token=${encodeURIComponent(info.token)}"></script>\n` +
        "    <!-- Head from Qualified (saved settings embedded); widget assets below are self-hosted. -->\n",
    );
  writeFileSync(`${site}/self-hosted-token-head.html`, brand(tokenHead, "self-hosted-token-head"));
  console.log("Wrote site/self-hosted-token-head.html (Qualified docking.js?token= head, self-hosted widget)");
}
