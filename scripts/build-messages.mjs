// Builds site/<page>/frame.html + panda.css + states.js from scripts/<page>/dump/, for the
// timeline pages: Messages (the default) and Cards.
//
// The dump is the real PiperX messenger (Main) as fireball renders it, one conversation per state
// (see scripts/<page>/zz_<page>_static_dump.test.tsx), so the markup carries the app's own hashed
// Panda class names and panda.css is the app's own stylesheet for them.
//
// The frame puts the markup where production does: inside an open shadow root on
// #qualified-multimodal-host, with the host's production inline style, as the Multimodal page
// does. The theme's --q-* properties go on the host, as applyThemeCssVars sets them.
//
//   npm run messages:build     # rebuild Messages from the committed dump
//   npm run cards:build        # the same for Cards (node scripts/build-messages.mjs cards)
//   npm run messages:refresh   # re-capture from fireball first, then build (cards:refresh too)
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PAGES = {
  messages: { title: "PiperX messages (static)", global: "PASTURE_MESSAGES", what: "Messages" },
  cards: { title: "PiperX cards (static)", global: "PASTURE_CARDS", what: "Cards" },
};
const page = process.argv[2] || "messages";
if (!PAGES[page]) throw new Error(`Unknown page "${page}"; expected one of ${Object.keys(PAGES).join(", ")}.`);
const { title, global, what } = PAGES[page];

const repo = fileURLToPath(new URL("..", import.meta.url));
const dump = `${repo}scripts/${page}/dump`;
const out = `${repo}site/${page}`;

const read = (name) => readFileSync(`${dump}/${name}`, "utf8");
// assets: placeholder URL -> local file, for images the dump puts in its messages.
const { layouts, states, themes, assets = {} } = JSON.parse(read("states.json"));
const sha = existsSync(`${dump}/fireball-sha.txt`) ? read("fireball-sha.txt").trim() : "unknown";

// The mock avatars and the dump's images are example.com; use local files so the frame makes no
// request for them. Nothing else in the capture is changed.
const LOCAL = [
  ["https://example.com/avatar.png", "../img/team/1.png"],
  ["https://example.com/rep.png", "../img/team/2.png"],
  ...Object.entries(assets),
];
const markup = (layout, state) => {
  const html = read(`${layout}--${state}.html`);
  if (!html.includes("MessageEntry.Container")) throw new Error(`${layout}--${state}.html has no messages; the capture is empty.`);
  return LOCAL.reduce((text, [from, to]) => text.split(from).join(to), html);
};

mkdirSync(out, { recursive: true });
copyFileSync(`${dump}/panda.css`, `${out}/panda.css`);
writeFileSync(
  `${out}/states.js`,
  `// GENERATED by scripts/build-messages.mjs: the captured layouts, conversations and themes the ${what} page offers.\n` +
    `window.${global} = ${JSON.stringify({ sha, layouts, states, themes: themes.map(({ id, label }) => ({ id, label })) }, null, 2)};\n`,
);

const templates = layouts
  .flatMap((layout) =>
    states.map(
      (state) =>
        `    <!-- ${layout.label}: ${state.label} -->\n    <template id="state-${layout.id}--${state.id}">${markup(layout.id, state.id)}</template>`,
    ),
  )
  .join("\n");

const frame = `<!doctype html>
<!-- GENERATED by scripts/build-messages.mjs from fireball ${sha}. Don't edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <!-- Inter, the messenger's font. Production's host.string.scss only declares Inter's
         @font-face rules in the light DOM; this is the same font from Google. -->
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" />
    <style>
      /* Frame only: the page behind the messenger. */
      html,
      body {
        margin: 0;
        min-height: 100%;
        background: #e9e2d6;
      }
    </style>
  </head>
  <body>
    <!-- The host as multimodal.ts creates it: production's inline style and an open shadow root
         that delegates focus. As on the Multimodal page, there's no focus gate, so the host has
         no tabindex="-1" and Tab reaches the messenger's controls directly. -->
    <div
      id="qualified-multimodal-host"
      style="position: fixed; top: 0; left: 0; width: var(--q-visible-viewport-width, 100%); height: 100%; contain: layout; pointer-events: none; z-index: 2147483640"
    ></div>

${templates}

    <script>
      (() => {
        const LAYOUTS = ${JSON.stringify(layouts.map(({ id }) => id))};
        const STATES = ${JSON.stringify(states.map(({ id }) => id))};
        const THEMES = ${JSON.stringify(Object.fromEntries(themes.map(({ id, vars }) => [id, vars])))};
        const params = new URLSearchParams(location.search);
        const pick = (list, value) => (list.includes(value) ? value : list[0]);
        const layout = pick(LAYOUTS, params.get("layout"));
        const state = pick(STATES, params.get("state"));
        const theme = pick(Object.keys(THEMES), params.get("theme"));
        const host = document.getElementById("qualified-multimodal-host");
        if (!host.attachShadow) {
          document.body.textContent = "This browser has no shadow DOM.";
          return;
        }
        host.dataset.state = state;
        // The theme, as Piper sets it: custom properties on the host, inherited into the shadow root.
        for (const [name, value] of Object.entries(THEMES[theme])) host.style.setProperty(name, value);
        const root = host.attachShadow({ mode: "open", delegatesFocus: true });
        const sheet = document.createElement("link");
        sheet.rel = "stylesheet";
        sheet.href = "panda.css";
        // AppLayout's PointerEventsGate: boxless, takes pointer events back from the host.
        const gate = document.createElement("div");
        gate.style.cssText = "display: contents; pointer-events: auto";
        // Insert the markup once the stylesheet has loaded, as in production, where the widget's
        // CSS is in place before the messenger renders; inserted first, transitions animate from
        // browser defaults.
        const insert = () => {
          gate.append(document.getElementById("state-" + layout + "--" + state).content.cloneNode(true));
          root.append(gate);
        };
        sheet.addEventListener("load", insert, { once: true });
        sheet.addEventListener("error", insert, { once: true });
        root.append(sheet);
      })();
    </script>
  </body>
</html>
`;

writeFileSync(`${out}/frame.html`, frame);
console.log(
  `Built site/${page}/frame.html (${layouts.length} layouts x ${states.length} states, ${themes.length} themes) and panda.css from fireball ${sha}`,
);
