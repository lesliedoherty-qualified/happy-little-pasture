// Builds site/multimodal/frame.html + site/multimodal/panda.css from scripts/multimodal/dump/.
//
// The dump is the real PiperX messenger (Main) as fireball renders it in TEXT mode (see
// scripts/multimodal/zz_multimodal_static_dump.test.tsx), so the markup carries the app's own
// hashed Panda class names and panda.css is the app's own stylesheet for them.
//
// The frame puts the markup where production does: inside an open shadow root on
// #qualified-multimodal-host, with the host's production inline style. So :host rules,
// custom properties inherited from the host and ::part() behave as on a customer's page.
//
//   npm run multimodal:build     # rebuild from the committed dump
//   npm run multimodal:refresh   # re-capture from fireball first, then build
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("..", import.meta.url));
const dump = `${repo}scripts/multimodal/dump`;
const out = `${repo}site/multimodal`;

const read = (name) => readFileSync(`${dump}/${name}`, "utf8");
const states = JSON.parse(read("states.json"));
const sha = existsSync(`${dump}/fireball-sha.txt`) ? read("fireball-sha.txt").trim() : "unknown";

// The mock store's avatar is example.com; use a local portrait so the frame makes no request
// for it. Nothing else in the capture is changed.
const AVATAR = "https://example.com/avatar.png";
const markup = (id) => {
  const html = read(`${id}.html`);
  if (!html.includes("part=")) throw new Error(`${id}.html has no parts; the capture is empty.`);
  return html.split(AVATAR).join("../img/team/1.png");
};

// The hooks the frame sets on the host, from QAI-6788's DEVELOPMENT.md "Host-page CSS hooks".
// Query parameter = the variable without its leading --q-.
const HOOKS = [
  "toolbar-background",
  "toolbar-text-color",
  "toolbar-secondary-text-color",
  "toolbar-button-hover-background",
];

mkdirSync(out, { recursive: true });
copyFileSync(`${dump}/panda.css`, `${out}/panda.css`);
writeFileSync(
  `${out}/states.js`,
  "// GENERATED by scripts/build-multimodal.mjs: the captured states the Multimodal page offers.\n" +
    `window.PASTURE_MULTIMODAL = ${JSON.stringify({ sha, hooks: HOOKS, states }, null, 2)};\n`,
);

const frame = `<!doctype html>
<!-- GENERATED by scripts/build-multimodal.mjs from fireball ${sha}. Don't edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>PiperX messenger (static)</title>
    <!-- Inter, the messenger's font. Production's host.string.scss only declares Inter's
         @font-face rules in the light DOM; this is the same font from Google. -->
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" />
    <style>
      /* Frame only: the page behind the messenger. */
      html,
      body {
        margin: 0;
        min-height: 100%;
        background: #e9e2d6;
      }
    </style>
  </head>
  <body>
    <!-- The host as multimodal.ts creates it: production's inline style, an open shadow root
         that delegates focus, and the widget's stylesheet inside it. One difference: production
         also sets tabindex="-1", which takes the shadow tree out of Tab order, and relays focus in
         with utils/focus_gate.ts. There's no focus gate here, so the host has no tabindex and
         Tab reaches the messenger's controls directly. -->
    <div
      id="qualified-multimodal-host"
      style="position: fixed; top: 0; left: 0; width: var(--q-visible-viewport-width, 100%); height: 100%; contain: layout; pointer-events: none; z-index: 2147483640"
    >
      <template shadowrootmode="open" shadowrootdelegatesfocus>
        <link rel="stylesheet" href="panda.css" />
        <!-- AppLayout's PointerEventsGate: boxless, takes pointer events back from the host. -->
        <div data-pasture-gate style="display: contents; pointer-events: auto"></div>
      </template>
    </div>

${states.map(({ id, label }) => `    <!-- ${label} -->\n    <template id="state-${id}">${markup(id)}</template>`).join("\n")}

    <script>
      (() => {
        const STATES = ${JSON.stringify(states.map(({ id }) => id))};
        const HOOKS = ${JSON.stringify(HOOKS)};
        const params = new URLSearchParams(location.search);
        const state = STATES.includes(params.get("state")) ? params.get("state") : STATES[0];
        const host = document.getElementById("qualified-multimodal-host");
        if (!host.shadowRoot) {
          document.body.insertAdjacentHTML("afterbegin", "<p>This browser has no declarative shadow DOM.</p>");
          return;
        }
        host.dataset.state = state;
        host.shadowRoot
          .querySelector("[data-pasture-gate]")
          .replaceChildren(document.getElementById("state-" + state).content.cloneNode(true));
        // Blank or missing means unset, so the widget's own default applies.
        for (const hook of HOOKS) {
          const value = params.get(hook);
          if (value) host.style.setProperty("--q-" + hook, value);
        }
      })();
    </script>
  </body>
</html>
`;

writeFileSync(`${out}/frame.html`, frame);
console.log(`Built site/multimodal/frame.html (${states.map((s) => s.id).join(", ")}) and panda.css from fireball ${sha}`);
